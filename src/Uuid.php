namespace GlpiPlugin\Clone;

/**
 * Server-side UUID v4 generator, used only as a fallback by the ajax
 * controller when the client did not supply a propagation_uuid (e.g. an
 * older cached clone.js). A server-generated fallback cannot make a retry
 * idempotent -- each request gets its own -- it exists purely so a missing
 * client value degrades to "works, without retry protection" instead of
 * hard-failing the request.
 */
final class Uuid
{
    public static function v4(): string
    {
        $data = random_bytes(16);
        $data[6] = chr((ord($data[6]) & 0x0f) | 0x40);
        $data[8] = chr((ord($data[8]) & 0x3f) | 0x80);

        return vsprintf('%s%s-%s-%s-%s-%s%s%s', str_split(bin2hex($data), 4));
    }

    public static function isValid(?string $value): bool
    {
        if ($value === null) {
            return false;
        }

        return preg_match('/^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i', $value) === 1;
    }
}
